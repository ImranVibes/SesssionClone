/**
 * SessionClone - Advanced Multi-Format Cookie & Storage Engine
 * Supports:
 * - SessionClone Universal Bundle (.json)
 * - Cookie-Editor JSON
 * - EditThisCookie JSON
 * - Quick Cookie Manager (JSON / Key-Value)
 * - Netscape / curl (cookies.txt with #HttpOnly_ prefixes)
 * - HTTP Cookie & Set-Cookie headers
 * - Plain JSON Storage dictionaries
 */

(function (global) {
  'use strict';

  /**
   * Determine valid URL for chrome.cookies.set / remove
   */
  function getCookieUrl(cookie, fallbackTabUrl) {
    if (cookie.url && typeof cookie.url === 'string' && (cookie.url.startsWith('http://') || cookie.url.startsWith('https://'))) {
      return cookie.url;
    }

    let protocol = 'https:';
    let host = '';

    if (fallbackTabUrl) {
      try {
        const parsed = new URL(fallbackTabUrl);
        protocol = parsed.protocol;
        host = parsed.hostname;
      } catch (e) {}
    }

    if (cookie.secure !== undefined) {
      protocol = cookie.secure ? 'https:' : 'http:';
    }

    let domain = cookie.domain || cookie.host || host || 'localhost';
    if (domain.startsWith('.')) {
      domain = domain.substring(1);
    }

    const path = (cookie.path && cookie.path.startsWith('/')) ? cookie.path : '/';
    return `${protocol}//${domain}${path}`;
  }

  /**
   * Sanitize a cookie object for chrome.cookies.set
   */
  function sanitizeCookieForSet(rawCookie, tabUrl) {
    const sanitized = {
      name: String(rawCookie.name || ''),
      value: String(rawCookie.value !== undefined ? rawCookie.value : ''),
      path: (rawCookie.path && rawCookie.path.startsWith('/')) ? rawCookie.path : '/'
    };

    // SameSite & Secure rules
    let sameSite = rawCookie.sameSite;
    if (typeof sameSite === 'string') {
      sameSite = sameSite.toLowerCase();
      if (sameSite === 'none' || sameSite === 'no_restriction') {
        sanitized.sameSite = 'no_restriction';
        sanitized.secure = true;
      } else if (sameSite === 'lax') {
        sanitized.sameSite = 'lax';
      } else if (sameSite === 'strict') {
        sanitized.sameSite = 'strict';
      } else {
        sanitized.sameSite = 'unspecified';
      }
    }

    if (sanitized.secure === undefined) {
      if (rawCookie.secure !== undefined && rawCookie.secure !== null) {
        sanitized.secure = Boolean(rawCookie.secure);
      } else if (rawCookie.isSecure !== undefined) {
        sanitized.secure = Boolean(rawCookie.isSecure);
      } else if (tabUrl && tabUrl.startsWith('https://')) {
        sanitized.secure = true;
      }
    }

    // URL resolution
    const url = getCookieUrl({ ...rawCookie, secure: sanitized.secure }, tabUrl);
    sanitized.url = url;

    // Domain & HostOnly handling (strip leading dot for Firefox API compatibility)
    const isHostOnly = rawCookie.hostOnly === true || rawCookie.isHostOnly === true;
    const domainVal = rawCookie.domain || rawCookie.host;
    if (!isHostOnly && domainVal) {
      sanitized.domain = String(domainVal).trim().replace(/^\./, '');
    }

    if (rawCookie.httpOnly !== undefined) {
      sanitized.httpOnly = Boolean(rawCookie.httpOnly);
    } else if (rawCookie.isHttpOnly !== undefined) {
      sanitized.httpOnly = Boolean(rawCookie.isHttpOnly);
    }

    // Expiration date (normalize ms to sec if needed)
    const isSession = rawCookie.session === true || rawCookie.isSession === true || (!rawCookie.expirationDate && !rawCookie.expires && rawCookie.session !== false);
    const expRaw = rawCookie.expirationDate !== undefined ? rawCookie.expirationDate : rawCookie.expires;
    if (!isSession && expRaw !== undefined) {
      let exp = Number(expRaw);
      if (exp > 32503680000) {
        exp = Math.floor(exp / 1000);
      }
      if (!isNaN(exp) && exp > 0) {
        sanitized.expirationDate = exp;
      }
    }

    if (rawCookie.storeId) {
      sanitized.storeId = rawCookie.storeId;
    }

    return sanitized;
  }

  /**
   * Export to Netscape / curl format (cookies.txt)
   * Session cookies keep expiration 0 (the standard marker for a session cookie),
   * so a round-trip never turns an ephemeral cookie into a permanent one.
   */
  function exportToNetscape(cookies) {
    const lines = [
      '# Netscape HTTP Cookie File',
      '# https://curl.se/docs/http-cookies.html',
      '# Generated by SessionClone',
      ''
    ];

    for (const c of cookies) {
      const domain = c.domain || '';
      const prefix = c.httpOnly ? '#HttpOnly_' : '';
      const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
      const path = c.path || '/';
      const secure = c.secure ? 'TRUE' : 'FALSE';
      const isSession = c.session === true || !c.expirationDate;
      const expiration = isSession ? 0 : Math.floor(c.expirationDate);
      const name = c.name || '';
      const value = c.value || '';

      lines.push(`${prefix}${domain}\t${flag}\t${path}\t${secure}\t${expiration}\t${name}\t${value}`);
    }

    return lines.join('\n');
  }

  /**
   * Parse Netscape / curl format (cookies.txt) including #HttpOnly_ prefixes
   */
  function parseNetscape(text) {
    const cookies = [];
    const lines = text.split('\n');

    for (let line of lines) {
      line = line.trim();
      if (!line) continue;

      let isHttpOnly = false;
      if (line.startsWith('#HttpOnly_')) {
        isHttpOnly = true;
        line = line.substring(10);
      } else if (line.startsWith('#')) {
        continue;
      }

      const parts = line.split('\t');
      if (parts.length >= 7) {
        const domain = parts[0];
        const hostOnly = parts[1].toUpperCase() === 'FALSE' && !domain.startsWith('.');
        const path = parts[2] || '/';
        const secure = parts[3].toUpperCase() === 'TRUE';
        const expirationDate = parseInt(parts[4], 10);
        const name = parts[5];
        const value = parts.slice(6).join('\t');

        cookies.push({
          domain: domain,
          hostOnly: hostOnly,
          path: path,
          secure: secure,
          httpOnly: isHttpOnly,
          sameSite: 'unspecified',
          expirationDate: !isNaN(expirationDate) && expirationDate > 0 ? expirationDate : undefined,
          session: isNaN(expirationDate) || expirationDate <= 0,
          name: name,
          value: value
        });
      }
    }

    return cookies;
  }

  /**
   * Export to HTTP Header string
   */
  function exportToHeaderString(cookies, includeHeaderName = true) {
    const pairs = cookies.map(c => `${c.name}=${c.value}`);
    const cookieStr = pairs.join('; ');
    return includeHeaderName ? `Cookie: ${cookieStr}` : cookieStr;
  }

  /**
   * Parse HTTP `Cookie:` header lines or `Set-Cookie:` lines.
   * Set-Cookie attributes (Path, Domain, Expires, Max-Age, Secure, HttpOnly, SameSite)
   * are preserved instead of being discarded.
   * @param {string} text
   * @param {string} [currentUrl] Active tab URL, used as fallback domain
   */
  const COOKIE_ATTRIBUTE_KEYS = ['domain', 'path', 'expires', 'max-age', 'samesite', 'secure', 'httponly', 'priority', 'partitioned'];

  function parseHeaderString(text, currentUrl = '') {
    const cookies = [];

    let fallbackDomain;
    let fallbackProtocol;
    try {
      const u = new URL(currentUrl);
      fallbackDomain = u.hostname;
      fallbackProtocol = u.protocol;
    } catch (e) {
      // Not a full URL - accept a bare hostname such as `example.com`
      const bare = String(currentUrl || '').trim().replace(/^\./, '');
      if (bare && !bare.includes('/') && !bare.includes(' ')) {
        fallbackDomain = bare;
      }
    }

    const lines = text.split('\n');

    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line) continue;

      const lower = line.toLowerCase();
      let isSetCookie = false;
      let body = line;

      if (lower.startsWith('cookie:')) {
        body = line.substring(7).trim();
      } else if (lower.startsWith('set-cookie:')) {
        isSetCookie = true;
        body = line.substring(11).trim();
      }

      const segments = body.split(';');
      const pairs = [];

      for (const seg of segments) {
        const s = seg.trim();
        if (!s) continue;
        const eq = s.indexOf('=');
        if (eq === -1) {
          // Flag-only Set-Cookie attribute such as `Secure` or `HttpOnly`
          pairs.push({ key: s.toLowerCase(), value: '', raw: s });
        } else {
          pairs.push({
            key: s.substring(0, eq).trim(),
            value: s.substring(eq + 1).trim(),
            raw: s
          });
        }
      }
      if (pairs.length === 0) continue;

      if (!isSetCookie) {
        // A Cookie: header (or a bare `name=value; name2=value2` list):
        // every pair is a cookie. Secure/HttpOnly markers found on the same
        // line are applied to all of that line's cookies.
        const lineFlags = {};
        const lineCookies = [];
        for (const p of pairs) {
          if (!p.key) continue;
          const k = p.key.toLowerCase();
          if (k === 'secure') { lineFlags.secure = true; continue; }
          if (k === 'httponly') { lineFlags.httpOnly = true; continue; }
          if (COOKIE_ATTRIBUTE_KEYS.includes(k)) continue;
          const cookie = {
            name: p.key,
            value: p.value,
            domain: fallbackDomain,
            path: '/',
            sameSite: 'unspecified',
            session: true
          };
          if (fallbackProtocol === 'https:') cookie.secure = true;
          lineCookies.push(cookie);
        }
        for (const cookie of lineCookies) {
          if (lineFlags.secure) cookie.secure = true;
          if (lineFlags.httpOnly) cookie.httpOnly = true;
          cookies.push(cookie);
        }
        continue;
      }

      // Set-Cookie: first pair is the cookie, the rest are attributes.
      const head = pairs[0];
      if (!head.key) continue;

      const cookie = {
        name: head.key,
        value: head.value,
        domain: fallbackDomain,
        path: '/',
        sameSite: 'unspecified',
        session: true
      };
      if (fallbackProtocol === 'https:') cookie.secure = true;

      for (let i = 1; i < pairs.length; i++) {
        const a = pairs[i];
        const key = a.key.toLowerCase();
        const val = a.value;

        switch (key) {
          case 'domain':
            if (val) {
              cookie.domain = val;
              cookie.hostOnly = false;
            }
            break;
          case 'path':
            if (val) cookie.path = val;
            break;
          case 'secure':
            cookie.secure = true;
            break;
          case 'httponly':
            cookie.httpOnly = true;
            break;
          case 'samesite': {
            const ss = val.toLowerCase();
            if (ss === 'none') cookie.sameSite = 'no_restriction';
            else if (ss === 'lax') cookie.sameSite = 'lax';
            else if (ss === 'strict') cookie.sameSite = 'strict';
            break;
          }
          case 'expires': {
            const t = Date.parse(val);
            if (!isNaN(t)) {
              cookie.expirationDate = Math.floor(t / 1000);
              cookie.session = false;
            }
            break;
          }
          case 'max-age': {
            const age = parseInt(val, 10);
            if (!isNaN(age)) {
              cookie.expirationDate = Math.floor(Date.now() / 1000) + age;
              cookie.session = false;
            }
            break;
          }
          default:
            break;
        }
      }

      cookies.push(cookie);
    }

    return cookies;
  }

  /**
   * Collect the distinct domains referenced by a cookie list.
   * Used to warn before injecting a session that belongs to another site.
   * @param {Array} cookies
   * @returns {string[]}
   */
  function getCookieDomains(cookies) {
    const set = new Set();
    if (Array.isArray(cookies)) {
      for (const c of cookies) {
        const d = (c && (c.domain || c.host)) || '';
        const clean = String(d).replace(/^\./, '').trim().toLowerCase();
        if (clean) set.add(clean);
      }
    }
    return Array.from(set).sort();
  }

  /**
   * Decide whether an imported cookie list is meant for the active domain.
   * Sub-domain matches (a.example.com vs example.com) are considered compatible.
   * @param {string} activeDomain
   * @param {Array} cookies
   * @returns {{ mismatch: boolean, imported: string[], active: string }}
   */
  function checkDomainMismatch(activeDomain, cookies) {
    const active = String(activeDomain || '').replace(/^\./, '').toLowerCase().trim();
    const imported = getCookieDomains(cookies);
    if (!active || imported.length === 0) {
      return { mismatch: false, imported, active };
    }
    const compatible = imported.some(d => d === active || d.endsWith('.' + active) || active.endsWith('.' + d));
    return { mismatch: !compatible, imported, active };
  }

  /**
   * Universal Smart Parser: Detects and normalizes any session/cookie/storage input
   * @param {string} rawText
   * @param {string} [activeDomain]
   * @returns {{ format: string, cookies: Array, localStorage: Object, sessionStorage: Object }}
   */
  function parseUniversalPayload(rawText, activeDomain = '') {
    const clean = (rawText || '').trim();
    if (!clean) {
      return { format: 'empty', cookies: [], localStorage: {}, sessionStorage: {} };
    }

    // 1. Encrypted payload
    if (clean.startsWith('SESSIONCLONE_ENC:')) {
      return { format: 'encrypted', encryptedData: clean, cookies: [], localStorage: {}, sessionStorage: {} };
    }

    // 2. JSON Structures
    if ((clean.startsWith('{') && clean.endsWith('}')) || (clean.startsWith('[') && clean.endsWith(']'))) {
      try {
        const parsed = JSON.parse(clean);

        // A. SessionClone Universal Bundle
        if (parsed && parsed.type === 'SessionCloneBundle') {
          return {
            format: 'bundle',
            cookies: Array.isArray(parsed.cookies) ? parsed.cookies : [],
            localStorage: parsed.localStorage || {},
            sessionStorage: parsed.sessionStorage || {},
            sourceDomain: parsed.domain || ''
          };
        }

        // A2. Generic `{ cookies: [...] }` wrapper (several exporters use this)
        if (parsed && !Array.isArray(parsed) && Array.isArray(parsed.cookies)) {
          return {
            format: 'bundle',
            cookies: parsed.cookies,
            localStorage: parsed.localStorage || parsed.local || {},
            sessionStorage: parsed.sessionStorage || parsed.session || {},
            sourceDomain: parsed.domain || parsed.origin || ''
          };
        }

        // B. Array of Cookies (Cookie-Editor, EditThisCookie, Quick Cookie Manager)
        if (Array.isArray(parsed)) {
          const normalizedCookies = parsed
            .filter(c => c && typeof c === 'object' && c.name !== undefined)
            .map(c => ({
              name: c.name || '',
              value: c.value !== undefined ? c.value : '',
              domain: c.domain || c.host || activeDomain || undefined,
              path: c.path || '/',
              secure: c.secure !== undefined ? Boolean(c.secure) : (c.isSecure !== undefined ? Boolean(c.isSecure) : undefined),
              httpOnly: c.httpOnly !== undefined ? Boolean(c.httpOnly) : Boolean(c.isHttpOnly),
              sameSite: c.sameSite || 'unspecified',
              session: Boolean(c.session || c.isSession),
              expirationDate: c.expirationDate || c.expires,
              hostOnly: Boolean(c.hostOnly || c.isHostOnly),
              storeId: c.storeId
            }));

          return {
            format: 'cookie_editor',
            cookies: normalizedCookies,
            localStorage: {},
            sessionStorage: {}
          };
        }

        // C. Plain JSON dictionary (Storage or Single Cookie object)
        if (typeof parsed === 'object' && parsed !== null) {
          // If it looks like a single cookie:
          if (parsed.name && parsed.value !== undefined) {
            return {
              format: 'cookie_editor',
              cookies: [parsed],
              localStorage: {},
              sessionStorage: {}
            };
          }

          // Otherwise treat as localStorage key-value map
          return {
            format: 'json_storage',
            cookies: [],
            localStorage: parsed,
            sessionStorage: {}
          };
        }
      } catch (e) {}
    }

    // 3. Netscape cookies.txt
    if (clean.startsWith('# Netscape HTTP Cookie File') || (clean.includes('\t') && clean.split('\n').some(l => l.split('\t').length >= 6))) {
      const cookies = parseNetscape(clean);
      return {
        format: 'netscape',
        cookies: cookies,
        localStorage: {},
        sessionStorage: {}
      };
    }

    // 4. Raw HTTP Header / Key-Value Pairs
    if (clean.toLowerCase().startsWith('cookie:') || clean.toLowerCase().startsWith('set-cookie:') || (clean.includes('=') && !clean.includes('{'))) {
      const cookies = parseHeaderString(clean, activeDomain);
      if (cookies.length > 0) {
        return {
          format: 'header',
          cookies: cookies,
          localStorage: {},
          sessionStorage: {}
        };
      }
    }

    return {
      format: 'unknown',
      cookies: [],
      localStorage: {},
      sessionStorage: {}
    };
  }

  /**
   * Fast format detection
   */
  function detectFormat(raw) {
    const result = parseUniversalPayload(raw);
    return result.format;
  }

  function getCookieSize(cookie) {
    const size = (cookie.name ? cookie.name.length : 0) + (cookie.value ? cookie.value.length : 0);
    if (size < 1024) return `${size} B`;
    return `${(size / 1024).toFixed(2)} KB`;
  }

  function getStorageItemSize(key, value) {
    const size = (key ? key.length : 0) + (value ? value.length : 0);
    if (size < 1024) return `${size} B`;
    if (size < 1024 * 1024) return `${(size / 1024).toFixed(2)} KB`;
    return `${(size / (1024 * 1024)).toFixed(2)} MB`;
  }

  const CookieUtils = {
    getCookieUrl,
    sanitizeCookieForSet,
    exportToNetscape,
    parseNetscape,
    exportToHeaderString,
    parseHeaderString,
    getCookieDomains,
    checkDomainMismatch,
    parseUniversalPayload,
    detectFormat,
    getCookieSize,
    getStorageItemSize
  };

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = CookieUtils;
  } else {
    global.CookieUtils = CookieUtils;
  }
})(typeof self !== 'undefined' ? self : this);
